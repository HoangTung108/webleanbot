import { fireEvent, render, screen, cleanup } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { RoutePlannerPanel } from './RoutePlannerPanel';
import type { SimulatorRenderer } from './renderer';
import { RobotSimulator } from './robotSimulator';

afterEach(cleanup);
it('selects, drags, sets arrival heading and deletes a waypoint without placing the robot', () => {
  const sim = new RobotSimulator(); sim.setPose({ x: 400, y: 400, heading: 0 });
  const canvas = document.createElement('canvas');
  const placement = vi.fn(); canvas.addEventListener('pointerdown', placement);
  const renderer = { render: vi.fn(), plannedRoute: [], clientToBoard: (x: number, y: number) => ({ x, y }) } as unknown as SimulatorRenderer;
  const props = { simulator: sim, renderer, canvas, locked: false, onRun: vi.fn() };
  const view = render(<RoutePlannerPanel {...props} />);
  fireEvent.click(screen.getByRole('button', { name: /0 b/ }));
  fireEvent.click(screen.getByRole('button', { name: 'Preview C++' }));
  const pointer = (type: string, x: number, y: number) => fireEvent(canvas, new MouseEvent(type, { clientX: x, clientY: y, button: 0, bubbles: true }));
  fireEvent.click(screen.getByText('Vẽ đường'));
  pointer('pointerdown', 500, 400);
  pointer('pointerdown', 600, 400);
  fireEvent.click(screen.getByText('Sửa điểm'));
  pointer('pointerdown', 500, 400);
  pointer('pointermove', 500, 500);
  pointer('pointerup', 500, 500);
  expect(screen.getByLabelText('Tọa độ Y')).toHaveValue(500);
  fireEvent.change(screen.getByLabelText('Tọa độ Y'), { target: { value: '400' } });
  fireEvent.click(screen.getByLabelText('Quay khi đến điểm'));
  fireEvent.click(screen.getByRole('button', { name: 'Chỉnh hướng tại điểm' }));
  fireEvent.change(screen.getByLabelText('Nhập góc robot'), { target: { value: '90' } });
  const preview = screen.getByLabelText('Code C++ lộ trình') as HTMLTextAreaElement;
  expect(preview.value).toBe('move_tank(2000, 2000, 10.000);\nturn_two_wheels(2000, 90.00);\nturn_two_wheels(2000, -90.00);\nmove_tank(2000, 2000, 10.000);');
  expect(placement).not.toHaveBeenCalled();
  view.rerender(<RoutePlannerPanel {...props} locked />);
  expect(screen.getByText('Xóa điểm')).toBeDisabled();
  pointer('pointerdown', 500, 400); pointer('pointermove', 800, 800);
  expect(screen.getByLabelText('Tọa độ Y')).toHaveValue(400);
  view.rerender(<RoutePlannerPanel {...props} />);
  fireEvent.click(screen.getByText('Xóa điểm'));
  expect(preview.value).toBe('move_tank(2000, 2000, 20.000);');
});
it('draws points without moving the robot and executes ordered events from the captured start', () => {
  const sim = new RobotSimulator(); sim.setPose({ x: 400, y: 400, heading: 0 });
  const canvas = document.createElement('canvas');
  const placement = vi.fn(); canvas.addEventListener('pointerdown', placement);
  const renderer = { render: vi.fn(), plannedRoute: [], clientToBoard: (x: number, y: number) => ({ x, y }) } as unknown as SimulatorRenderer;
  const onRun = vi.fn();
  render(<RoutePlannerPanel simulator={sim} renderer={renderer} canvas={canvas} locked={false} onRun={onRun} />);
  fireEvent.click(screen.getByRole('button', { name: /0 b/ }));
  fireEvent.click(screen.getByRole('button', { name: 'Preview C++' }));
  fireEvent.click(screen.getByText('Vẽ đường'));
  fireEvent(canvas, new MouseEvent('pointerdown', { clientX: 500, clientY: 400, button: 0, bubbles: true }));
  expect(placement).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: 'Gắp' }));
  fireEvent.click(screen.getByRole('button', { name: 'Xoay' }));
  fireEvent.click(screen.getByRole('button', { name: 'Thả' }));
  const preview = screen.getByRole('textbox', { name: 'Code C++ lộ trình' }) as HTMLTextAreaElement;
  expect(preview.value).toBe('move_tank(2000, 2000, 10.000);\nclose_hand(90);\nturn_two_wheels(2000, 90.00);\nopen_hand();');
  expect(screen.queryByRole('button', { name: /copy|sao chép|tải/i })).toBeNull();
  fireEvent.click(screen.getByText('Chạy lộ trình'));
  expect(onRun).toHaveBeenCalledWith(expect.stringContaining('move_tank(2000, 2000, 10.000)'), expect.objectContaining({ x: 400, y: 400, heading: 0 }));
  expect(renderer.plannedRoute).toHaveLength(5);
});
